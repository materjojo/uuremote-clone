#!/usr/bin/env python3
"""Generate both field-name tables from recovered descriptors, including nested messages."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'analysis/official/gv-pb-descriptors.json'


def messages(files):
    def visit(message, parent=''):
        name = parent + message['name']
        yield name, message['fields']
        for child in message.get('nested', []):
            yield from visit(child, name + '.')
    return sorted(row for file in files for message in file['messages'] for row in visit(message))


def cpp(rows):
    lines = ['// Generated by scripts/gen_protocol_schema.py from the supplied Windows descriptors.',
             '#include "gvpb.h"', '#include <unordered_map>', '#include <string>', '',
             'namespace {', 'struct Entry { const char *name; int number; };',
             'const std::unordered_map<std::string, std::unordered_map<int, Entry>> kSchema = {']
    for name, fields in rows:
        entries = ','.join('{%d, {"%s", %d}}' % (f['number'], f['name'], f['number']) for f in fields)
        lines.append('  {"%s", {%s}},' % (name, entries))
    lines += ['};', '}', '''
const char *gvpb_schema_name(const char *message, int field) {
    if (!message) return nullptr;
    auto it = kSchema.find(message);
    if (it == kSchema.end()) return nullptr;
    auto fit = it->second.find(field);
    return fit == it->second.end() ? nullptr : fit->second.name;
}

int gvpb_schema_number(const char *message, const char *name) {
    if (!message || !name) return -1;
    auto it = kSchema.find(message);
    if (it == kSchema.end()) return -1;
    for (const auto &kv : it->second) if (std::string(kv.second.name) == name) return kv.first;
    return -1;
}

int gvpb_schema_message_count(void) { return static_cast<int>(kSchema.size()); }
''']
    return '\n'.join(lines)


def swift(rows):
    lines = ['// Generated by scripts/gen_protocol_schema.py from the supplied Windows descriptors.',
             'public enum GvSchema {', f'    public static let messageCount = {len(rows)}',
             '    public static let fields: [String: [Int: String]] = [']
    for name, fields in rows:
        pairs = ', '.join('%d: "%s"' % (f['number'], f['name']) for f in fields)
        lines.append('        "GvPb_%s": [%s],' % (name.replace('.', '_'), pairs if pairs else ':'))
    lines += ['    ]', '''
    private static func key(_ message: String) -> String {
        if message.hasPrefix("GvPb_") { return message }
        let short = message.hasPrefix("gv_pb.") ? String(message.dropFirst(6)) : message
        return "GvPb_" + short.replacingOccurrences(of: ".", with: "_")
    }

    public static func name(_ message: String, _ field: Int) -> String? {
        fields[key(message)]?[field]
    }

    public static func number(_ message: String, _ fieldName: String) -> Int? {
        fields[key(message)]?.first(where: { $0.value == fieldName })?.key
    }
}
''']
    # Foundation is needed only for name normalization, not the protocol table.
    lines.insert(1, 'import Foundation')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = messages(json.loads(SOURCE.read_text()))
    if len(rows) != 179 or len({row[0] for row in rows}) != 179:
        raise SystemExit('Unexpected recovered descriptor message inventory')
    for path, output in [(ROOT / 'core/src/schema.cpp', cpp(rows)),
                         (ROOT / 'Sources/UURemoteClone/Protocol/SchemaTable.swift', swift(rows))]:
        if args.check:
            if path.read_text() != output:
                raise SystemExit('Generated protocol table is stale: ' + str(path))
        else:
            path.write_text(output)
    print(f'{len(rows)} message field tables, including MumuSetting.MapKeyValueEntry and ScreenResolution')


if __name__ == '__main__':
    main()
